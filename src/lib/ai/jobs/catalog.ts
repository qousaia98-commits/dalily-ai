const BY_KEY = new Map(
  SERVICE_KNOWLEDGE_CATALOG.map((e) => [e.serviceKey, e]),
);

export function getServiceKnowledge(serviceKey: string): ServiceKnowledgeEntry | null {
  return BY_KEY.get(serviceKey) ?? null;
}

export function listServiceKnowledgeByCategory(
  categorySlug: string,
): ServiceKnowledgeEntry[] {
  return SERVICE_KNOWLEDGE_CATALOG.filter((e) => e.categorySlug === categorySlug);
}
