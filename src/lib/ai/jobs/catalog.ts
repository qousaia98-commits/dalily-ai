import type { PriceEstimate, ServiceKnowledgeEntry } from "@/lib/ai/jobs/types";

const SYP_DISCLAIMER_EN =
  "Estimated market range only — final quote depends on on-site inspection.";
const SYP_DISCLAIMER_AR =
  "نطاق سعري تقديري فقط — العرض النهائي يعتمد على المعاينة في الموقع.";

function syp(min: number, typical: number, max: number): PriceEstimate {
  return {
    min,
    typical,
    max,
    currency: "SYP",
    isRangeOnly: true,
    disclaimerEn: SYP_DISCLAIMER_EN,
    disclaimerAr: SYP_DISCLAIMER_AR,
  };
}

function minutes(
  min: number,
  typical: number,
  max: number,
): ServiceKnowledgeEntry["duration"] {
  return {
    minMinutes: min,
    typicalMinutes: typical,
    maxMinutes: max,
    labelEn: `${min}–${max} minutes`,
    labelAr: `${min}–${max} دقيقة`,
    unit: "minutes",
  };
}

function days(
  minDays: number,
  typicalDays: number,
  maxDays: number,
): ServiceKnowledgeEntry["duration"] {
  return {
    minMinutes: minDays * 24 * 60,
    typicalMinutes: typicalDays * 24 * 60,
    maxMinutes: maxDays * 24 * 60,
    labelEn: `${minDays}–${maxDays} days`,
    labelAr: `${minDays}–${maxDays} أيام`,
    unit: "days",
  };
}

